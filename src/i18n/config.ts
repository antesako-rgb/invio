/* ==========================================================================
   Locales
========================================================================== */

export const locales = [
  "hr",
  "en",
] as const;


/* ==========================================================================
   Locale Type
========================================================================== */

export type Locale =
  (typeof locales)[number];


/* ==========================================================================
   Default Locale
========================================================================== */

export const defaultLocale: Locale =
  "hr";


/* ==========================================================================
   Locale Validation
========================================================================== */

export function isSupportedLocale(
  locale: string
): locale is Locale {
  return locales.includes(
    locale as Locale
  );
}